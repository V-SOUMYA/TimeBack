// Copies data/providers.json into a browser script so the app also works
// when index.html is opened without the server (offline demo mode).
const fs = require('fs');
const path = require('path');
const data = fs.readFileSync(path.join(__dirname, '..', 'data', 'providers.json'), 'utf8');
const out = `// Generated by scripts/build-catalog.js from data/providers.json. Do not edit by hand.\nwindow.TIMEBACK_CATALOG = ${data.trim()};\n`;
fs.writeFileSync(path.join(__dirname, '..', 'public', 'shared', 'catalog.js'), out);
console.log('Wrote public/shared/catalog.js');
